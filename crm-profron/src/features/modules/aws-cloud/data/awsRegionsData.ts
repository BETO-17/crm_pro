export type RegionOperationalStatus = 'En uso' | 'Requiere revisión' | 'Disponible';

export interface RegionStatusDetails {
  status: RegionOperationalStatus;
  color: string;
  bg: string;
  border: string;
  dot: string;
}

export function getRegionStatus(
  regionCode: string,
  proposedRegionStr?: string | null,
  services: string[] = []
): RegionStatusDetails {
  const isTarget = proposedRegionStr ? proposedRegionStr.includes(regionCode) : false;

  if (isTarget) {
    if (services.length > 0) {
      return {
        status: 'En uso',
        color: '#15803D',
        bg: '#DCFCE7',
        border: '#86EFAC',
        dot: '#16A34A',
      };
    } else {
      return {
        status: 'Requiere revisión',
        color: '#B45309',
        bg: '#FEF3C7',
        border: '#FDE68A',
        dot: '#F59E0B',
      };
    }
  }

  return {
    status: 'Disponible',
    color: '#64748B',
    bg: '#F1F5F9',
    border: '#CBD5E1',
    dot: '#94A3B8',
  };
}
